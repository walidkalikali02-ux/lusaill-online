(() => {
  const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
  const stage = (prompt, answer, alternatives, art, explain, why) =>
    ({prompt,answer,options:[answer,...alternatives],art,explain,why});
  const count = (n, icon = '🐚') => stage(
    n ? 'تأمّل الصورة. كم قطعة ترى؟' : 'السلة فارغة. كم قطعة فيها؟',
    n,[n+1,n ? n-1 : 2],{type:'count',n,icon},
    n ? 'نلمس كل قطعة مرة واحدة. آخر عدد نصل إليه هو ' + ar(n) + '، وهو عدد القطع كلها.' : 'عندما لا توجد أي قطعة، نعبّر عن الكمية بالعدد صفر.',
    n ? ['هذا العدد يزيد عن عدد القطع بواحدة.','هذا العدد ينقص عن عدد القطع بواحدة.'] : ['لو وجدت قطعة واحدة لكان العدد واحدًا.','العدد اثنان يحتاج إلى قطعتين.']);
  const compare = (a,b) => {
    const choices = ['المجموعة الأولى','المجموعة الثانية','متساويتان'];
    const correct = a === b ? 2 : a > b ? 0 : 1;
    return stage('أيّ المجموعتين فيها قطع أكثر؟',choices[correct],choices.filter((_,i)=>i!==correct),
      {type:'compare',a,b},
      a === b ? 'كل قطعة في المجموعة الأولى لها قطعة تقابلها. لا يتبقّى شيء، إذن الكميتان متساويتان.' :
        'نصل كل قطعة بقطعة تقابلها. يتبقّى ' + ar(Math.abs(a-b)) + ' في المجموعة ' + (a>b?'الأولى':'الثانية') + '، فهي الأكثر.',
      choices.filter((_,i)=>i!==correct).map(choice=>choice==='متساويتان'?'توجد قطع بلا مقابل، إذن الكميتان مختلفتان.':'المجموعة التي اخترتها لا يبقى فيها شيء بعد المطابقة.'));
  };
  const calc = (a,b,subtract=false,skip=false) => {
    const result = subtract ? a-b : a+b;
    const symbol = subtract?'−':'+';
    return stage('ما ناتج ' + ar(a)+' '+symbol+' '+ar(b)+'؟',result,[result+1,result ? result-1 : 2],
      {type:subtract?'subtract':'add',a,b,skip},
      subtract ? 'بدأنا بـ '+ar(a)+'، وحذفنا '+ar(b)+'، فبقي '+ar(result)+'.' :
        'بدأنا بـ '+ar(a)+'، وأضفنا '+ar(b)+'، فأصبح المجموع '+ar(result)+'.',
      ['هذا العدد أكبر من الناتج بواحد.','هذا العدد '+(result?'أقل من الناتج بواحد.':'يعني أن شيئًا بقي، وقد أزلنا المجموعة كلها.')]);
  };
  const next = (start,step) => {
    const end=start+3*step;
    return stage('ما العدد التالي؟',end,[end+step,end-step],{type:'line',start,step},
      'نبدأ من '+ar(start)+' ونضيف '+ar(step)+' في كل قفزة. العدد التالي هو '+ar(end)+'.',
      ['هذا العدد يحتاج إلى قفزة إضافية.','هذا العدد هو الذي قبل الفراغ.']);
  };
  const place = (t,o) => stage('كوّنا '+ar(t)+' عشرات و'+ar(o)+' آحاد. ما العدد؟',
    10*t+o,[10*t+o+10,t+o],{type:'place',t,o},
    'كل حزمة فيها عشرة. قيمة العشرات '+ar(10*t)+'، ونضيف إليها '+ar(o)+' آحاد فيصبح العدد '+ar(10*t+o)+'.',
    ['في هذا العدد عشرة إضافية.','هذا الاختيار يحسب كل حزمة كأنها قطعة واحدة، وفيها عشر قطع.']);
  const tenCalc = (t,k,sub=false) => {
    const answer = (sub?t-k:t+k)*10;
    return stage('ما ناتج '+ar(t*10)+(sub?' − ':' + ')+ar(k*10)+'؟',answer,[answer+10,answer-10],
      {type:sub?'subtract':'add',a:t,b:k,skip:true},
      'كل حزمة تساوي عشرة. '+(sub?'حذفنا ':'أضفنا ')+ar(k)+' من الحزم، فأصبح لدينا '+ar(answer/10)+' عشرات. قيمتها '+ar(answer)+'.',
      ['هذا العدد يزيد عشرة عن عدد الحزم الناتج.','هذا العدد ينقص عشرة عن عدد الحزم الناتج.']);
  };
  const length = (n,object) => stage('كم مكعبًا نحتاج لقياس طول '+object+'؟',n,[n+1,n-1],{type:'length',n},
    'نبدأ من طرف الشريط ونضع مكعبات متساوية بلا فراغات. نحتاج '+ar(n)+' مكعبات حتى الطرف الآخر.',
    ['مكعب إضافي سيتجاوز نهاية الشريط.','سيبقى جزء من الشريط بلا مكعب.']);
  const time = (h,m) => {
    const stamp=(hour,minute)=>ar(hour)+':'+ar(String(minute).padStart(2,'0'));
    const nextHour=h%12+1;
    return stage('اقرأ الساعة في الرسم.',stamp(h,m),[stamp(nextHour,m),stamp(h,m?0:30)],{type:'clock',h,m},
      'العقرب الطويل عند '+(m?'٦، أي مرّ نصف ساعة':'١٢، أي لم تمر دقائق')+'. العقرب القصير '+(m?'تجاوز '+ar(h)+' ولم يصل إلى '+ar(nextHour):'يشير إلى '+ar(h))+'. الوقت '+stamp(h,m)+'.',
      ['العقرب القصير يشير إلى '+ar(h)+' أو تجاوزها فقط. الساعة التالية لم تبدأ بعد.','مكان العقرب الطويل هو الذي يحدّد إن كان الوقت تمام الساعة أم نصفها.']);
  };
  const shape = (name,sides) => stage('كم ضلعًا مستقيمًا لهذا الشكل؟',sides,[sides+1,sides?sides-1:2],{type:'shape',name,sides},
    sides?name+' له '+ar(sides)+' أضلاع مستقيمة. تَتبّع كل ضلع من رأس إلى رأس.':'حدّ الدائرة منحني بالكامل، لذلك ليس لها أضلاع مستقيمة.',
    ['العدد أكبر من عدد الأضلاع المستقيمة التي تتبّعناها.','هذا الاختيار لا يطابق عدد الأضلاع المستقيمة في الرسم.']);
  const solid = (name,answer,others) => stage('أيّ مجسّم يشبه هذا الشيء؟',answer,others,{type:'solid',name,answer},
    name+' يشبه '+answer+'. '+({'المكعب':'له ستة أوجه مربعة.','الكرة':'سطحها منحنٍ في كل الجهات.','الأسطوانة':'لها قاعدتان دائريتان وسطح منحنٍ.'}[answer]),
    others.map(other=>({'المكعب':'المكعب له أوجه مربعة، وهي لا تظهر هنا.','الكرة':'الكرة سطحها منحنٍ بالكامل، وهذا المجسّم له سطح مستوٍ.','الأسطوانة':'الأسطوانة لها قاعدتان دائريتان، ولا نرى قاعدتين دائريتين هنا.'}[other])));
  const parts = (n) => stage(n===2?'لو قسمنا المستطيل من المنتصف بخط واحد، كم جزءًا متساويًا ينتج؟':
    'لو قسمنا المستطيل من المنتصف بخط رأسي وخط أفقي، كم جزءًا متساويًا ينتج؟',n,[n+1,n===2?4:2],{type:'parts',n},
    'كل خط في الرسم يقسم الشكل إلى أجزاء متساوية المساحة. بعد العد نرى '+ar(n)+' أجزاء متساوية.',
    ['بعد تتبّع الخطوط ستجد أجزاء أقل من هذا العدد.','عُدّ المساحات داخل الشكل مرة واحدة لكل جزء.']);
  const pattern = (sequence,answer,alternatives) => stage('أيّ شكل يكمل النمط؟',answer,alternatives,{type:'pattern',sequence,answer},
    'نكرر نفس المجموعة من اليسار إلى اليمين. الشكل الذي يكمل المجموعة هو '+answer+'.',
    alternatives.map(()=> 'انظر إلى نفس المكان في المجموعة الأولى. الشكل فيه مختلف عن اختيارك.'));
  const lessons = [
    [1,'الأعداد حتى ٥','عُدّ قطعة واحدة في كل مرة.',[count(2),count(4,'🍎'),count(5,'⭐')]],
    [1,'الصفر والأعداد حتى ١٠','اربط الرقم بعدد الأشياء.',[count(0),count(7,'🍎'),count(10,'⭐')]],
    [1,'مقارنة المجموعات','طابق قطعة بقطعة لتعرف الأكثر.',[compare(4,6),compare(5,5),compare(7,4)]],
    [1,'الجمع حتى ١٠','اجمع مجموعتين بالقطع.',[calc(2,3),calc(4,4),calc(6,4)]],
    [1,'الطرح حتى ١٠','أزل قطعًا وعدّ ما بقي.',[calc(5,2,true),calc(7,7,true),calc(10,4,true)]],
    [1,'ترتيب الأعداد','تحرّك على خط الأعداد.',[next(0,1),next(4,1),next(7,1)]],
    [2,'الجمع حتى ٢٠','ابدأ بالعدد الأكبر وأكمل العد.',[calc(9,2),calc(10,5),calc(13,6)]],
    [2,'الطرح حتى ٢٠','اربط الطرح بإزالة مجموعة.',[calc(11,3,true),calc(15,5,true),calc(18,6,true)]],
    [2,'العد حتى ١٠٠','تابع القفزات بالآحاد والعشرات.',[next(17,1),next(30,10),next(70,10)]],
    [2,'العشرات والآحاد','كوّن الأعداد بالحزم والقطع.',[place(2,3),place(4,0),place(6,7)]],
    [2,'جمع العشرات','اجمع حزم العشرة.',[tenCalc(2,3),tenCalc(4,2),tenCalc(6,3)]],
    [2,'طرح العشرات','أزل حزمًا كاملة.',[tenCalc(5,2,true),tenCalc(7,3,true),tenCalc(9,4,true)]],
    [2,'قياس الأطوال','ضع وحدات القياس جنبًا إلى جنب.',[length(3,'البطاقة'),length(5,'القلم'),length(7,'المسطرة')]],
    [2,'قراءة الساعة','تتبّع العقرب القصير والطويل.',[time(3,0),time(7,30),time(12,30)]],
    [2,'الأشكال المستوية','تتبّع الأضلاع المستقيمة.',[shape('المثلث',3),shape('المربع',4),shape('الدائرة',0)]],
    [2,'المجسّمات','لاحظ الأسطح والأوجه.',[solid('حجر النرد','المكعب',['الكرة','الأسطوانة']),solid('كرة اللعب','الكرة',['المكعب','الأسطوانة']),solid('علبة العصير','الأسطوانة',['المكعب','الكرة'])]],
    [2,'الأجزاء المتساوية','قسّم شكلًا إلى أنصاف وأرباع.',[parts(2),parts(4)]],
    [2,'الأنماط المتكررة','اكتشف المجموعة التي تعيد نفسها.',[pattern(['●','▲','●'],'▲',['●','■']),pattern(['■','■','●','■','■'],'●',['■','▲']),pattern(['▲','●','■','▲','●'],'■',['▲','●'])]]
  ];
  window.mathLessons = lessons.sort((left,right)=>left[0]-right[0])
    .map(([term,title,goal,stages],index)=>({id:index+1,term,title,goal,stages}));
  window.mathUnits = [
    {term:1,title:'الأعداد والعدّ والمقارنة',ids:[1,2,3,6]},
    {term:1,title:'الجمع والطرح حتى ١٠',ids:[4,5]},
    {term:2,title:'الجمع والطرح حتى ٢٠',ids:[7,8]},
    {term:2,title:'الأعداد حتى ١٠٠ والقيمة المكانية',ids:[9,10]},
    {term:2,title:'جمع العشرات وطرحها',ids:[11,12]},
    {term:2,title:'القياس والوقت',ids:[13,14]},
    {term:2,title:'الأشكال والمجسّمات والأجزاء المتساوية',ids:[15,16,17]},
    {term:2,title:'الأنماط',ids:[18]}
  ];
  window.arNumber = ar;
})();

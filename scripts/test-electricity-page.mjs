import assert from 'node:assert/strict';
const origin = process.argv[2] ?? 'http://127.0.0.1:3017';
const path = '/articles/electricity-bill-inquiry';
const response = await fetch(origin + path);
assert.equal(response.status, 200);
const html = await response.text();
const schemas = [...html.matchAll(/<script type="application\/ld\+json">([^<]+)<\/script>/g)].map(match => JSON.parse(match[1]));
const types = schemas.map(schema => schema['@type']);
for (const type of ['Article','FAQPage','HowTo','BreadcrumbList']) assert.ok(types.includes(type), type);
const faq = schemas.find(schema => schema['@type'] === 'FAQPage');
assert.equal(faq.mainEntity.length, 8);
for (const entry of faq.mainEntity) assert.ok(html.includes(entry.name), 'Schema question visible');
assert.equal(schemas.find(schema => schema['@type'] === 'HowTo').step.length, 4);
assert.equal((html.match(/<h1(?:\s|>)/g) ?? []).length, 1);
assert.ok(/<html[^>]*lang="ar"[^>]*dir="rtl"/.test(html));
assert.ok(html.includes('rel="canonical" href="https://www.lusaill.online' + path + '"'));
assert.ok(/name="robots" content="index, follow/.test(html));
const title = html.match(/<title>(.*?)<\/title>/)[1];
const description = html.match(/name="description" content="([^"]+)"/)[1];
assert.ok(title.length <= 60, title);
assert.ok(description.length <= 155, description);
assert.ok(html.includes('electricity-cost-example.webp'));
assert.ok(html.includes('id="electricity-kwh"'));
const table = html.slice(html.indexOf('id="electricity-companies"'), html.indexOf('id="steps"'));
assert.equal((table.match(/<tr>/g) ?? []).length, 10);
const alias = await fetch(origin + '/services/electricity-bill-inquiry', {redirect:'manual'});
assert.equal(alias.status, 301);
assert.equal(new URL(alias.headers.get('location'), origin).pathname, path);
console.log(JSON.stringify({result:'PASS', titleLength:title.length, descriptionLength:description.length, companies:9, faq:8, howToSteps:4, schemaWordCount:schemas.find(s=>s['@type']==='Article').wordCount, alias:301}));

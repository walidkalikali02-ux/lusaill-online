import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile('lib/housing-press-update.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {applyHousingPressUpdate,housingPressUpdate:news}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const officialSources=[{label:'بيان سابق',url:'https://sis.gov.eg/',checkedAt:'2026-09-26'}];
const article={slug:'old-rent-housing-apply',title:'قديم',status:'published',sources:officialSources,summaryTable:[{label:'الموعد المعلن',value:'12 أكتوبر 2026 وفق المصدر السابق'}],faqs:[{question:'الموعد؟',answer:'12 أكتوبر 2026'}]};
const updated=applyHousingPressUpdate(article);
assert.equal(updated.sources,officialSources,'Press links must not be relabelled as official sources');
assert.equal(updated.sources[0].checkedAt,'2026-09-26','Do not invent a new official-source verification date');
assert.equal(updated.status,'published');
assert(updated.quickAnswer.includes('لم نتمكن')&&updated.quickAnswer.includes('تغطية أخرى'));
assert(updated.title.includes('متابعة خبر'));
assert(updated.metaDescription.length>=140&&updated.metaDescription.length<=155);
assert(updated.summaryTable[0].label.includes('السابق'));
assert(updated.faqs.some(f=>f.question.includes('هل تأكد')));
for(const suffix of ['eligibility','documents','post-office','track'])assert.equal(applyHousingPressUpdate({...article,slug:`old-rent-housing-${suffix}`}).updatedAt,news.updatedAt);
const unrelated={slug:'electricity-bill-inquiry',title:'الكهرباء'};assert.equal(applyHousingPressUpdate(unrelated),unrelated);
const deadlines=await readFile('lib/deadlines.ts','utf8');assert(deadlines.includes('"2026-10-12"')&&!deadlines.includes('2027-01'),'No unverified January countdown');
console.log('PASS: attributed housing follow-up, historical deadline, five guides, unchanged official checks and valid metadata length');

import assert from "node:assert/strict";
import { runLab, DEFAULT_LAB_INPUT } from "../lib/reality-lab/model.ts";
const input={...DEFAULT_LAB_INPUT,days:5,repetitions:3,seed:457};
const first=runLab(input);
const second=runLab(input);
assert.deepEqual(first,second,"Same seed must reproduce identical results");
assert.equal(first.daily.length,5);
assert.equal(first.branches.length,5);
assert.equal(first.provenance,"synthetic");
assert.ok(first.summary.requested>=first.summary.served);
assert.ok(first.summary.serviceRate>=0&&first.summary.serviceRate<=100);
assert.ok(first.summary.revenueQar>=0);
assert.ok(first.summary.roastKg>=0);
assert.ok(first.daily.every(d=>d.served+d.lostQueue+d.lostStock<=d.requested+1e-6));
assert.ok(first.branches.every(b=>b.endingStockKg>=-1e-8));
assert.throws(()=>runLab({...input,days:22}),/days/);
assert.throws(()=>runLab({...input,repetitions:100}),/repetitions/);
assert.throws(()=>runLab({...input,demandFactor:-1}),/demandFactor/);
assert.throws(()=>runLab({...input,branchOrdersPerDay:{alkhor:-1}}),/alkhor/);
const imported=runLab({...input,branchOrdersPerDay:{alkhor:100}});
assert.equal(imported.provenance,"partially_calibrated");
const delayed=runLab({...input,deliveryDays:4});
assert.ok(delayed.summary.lostStock>=0);
console.log("Lusaill Reality Lab: 14 core assertions passed");
